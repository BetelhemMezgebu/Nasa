function FilterBar({
  value,
  onChange,
  options = [],
  label = "Filter"
}) {
  return (
    <div className="filter-bar">
      <label>{label}</label>

      <select
        value={value}
        onChange={(event) =>
          onChange(event.target.value)
        }
      >
        {options.map((option) => (
          <option
            key={option.value}
            value={option.value}
          >
            {option.label}
          </option>
        ))}
      </select>
    </div>
  );
}

export default FilterBar;